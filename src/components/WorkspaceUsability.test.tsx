import { fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, beforeEach, expect, test } from 'vitest'
import App from '../App'

beforeEach(() => localStorage.clear())
afterEach(() => localStorage.clear())
const click = (name: string) => fireEvent.click(screen.getByRole('button', { name }))
const tab = (name: string) => fireEvent.click(screen.getByRole('tab', { name }))
function add(name: string, hours = '1') {
  tab('Workspace'); click('Add task')
  fireEvent.change(screen.getByLabelText(/^Task name/), { target: { value: name } })
  fireEvent.change(screen.getByLabelText(/^Estimated duration/), { target: { value: hours } }); click('Save task')
}
const bar = (id: string) => screen.getByRole('button', { name: new RegExp(`^${id} .*working hours; starts`) })

test('A01–A03 chart stays above the full editor, with one numbered details panel after the task list', () => {
  render(<App />); add('Research', '5'); add('Draft', '2')
  const overview = screen.getByRole('region', { name: 'Project overview' })
  const chart = screen.getByRole('region', { name: 'Gantt chart' })
  const tasks = screen.getByRole('region', { name: 'Tasks & schedule' })
  const details = screen.getByRole('region', { name: 'Task details' })
  expect(overview.compareDocumentPosition(chart) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy()
  expect(chart.compareDocumentPosition(tasks) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy()
  expect(tasks.compareDocumentPosition(details) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy()
  expect(within(chart).getByText('01 / Timeline')).toBeInTheDocument()
  expect(within(tasks).getByText('02 / Tasks & Schedule')).toBeInTheDocument()
  expect(within(details).getByText('03 / Task Details')).toBeInTheDocument()
  fireEvent.click(bar('T1'))
  expect(within(details).getByLabelText('Selected task details')).toHaveTextContent('T1 — Research')
  expect(within(chart).queryByLabelText('Selected task details')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('row', { name: 'T2 Draft' }).querySelector('td:last-of-type')!)
  expect(within(details).getByLabelText('Selected task details')).toHaveTextContent('T2 — Draft')
  expect(within(details).getByText('Total slack')).toBeInTheDocument()
  click('Edit T2')
  expect(within(tasks).getByRole('region', { name: 'Edit task T2' })).toBeInTheDocument()
  expect(chart.compareDocumentPosition(screen.getByRole('region', { name: 'Edit task T2' })) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy()
  click('Network / Critical Path')
  expect(within(screen.getByRole('region', { name: 'Network / Critical Path' })).getByText('01 / Timeline')).toBeInTheDocument()
  expect(screen.getAllByLabelText('Selected task details')).toHaveLength(1)
})

test('A04/A07 staged dependency changes leave committed dates intact; Escape restores saved/dirty state', () => {
  render(<App />); add('Research', '5'); add('Draft')
  tab('Files'); fireEvent.change(screen.getByLabelText('Saved plan name'), { target: { value: 'Clean plan' } }); click('Save As'); tab('Workspace')
  const before = bar('T2').getAttribute('aria-label')
  fireEvent.click(bar('T1'))
  click('T2 predecessors'); fireEvent.click(within(screen.getByRole('group', { name: 'T2 predecessor selection' })).getByText('T1 — Research'))
  expect(bar('T2')).toHaveAttribute('aria-label', before)
  expect(screen.getByText('Unsaved changes')).toBeInTheDocument()
  fireEvent.keyDown(screen.getByRole('checkbox', { name: 'T2 predecessor T1 — Research' }), { key: 'Escape' })
  expect(screen.getByText('Saved locally')).toBeInTheDocument()
  expect(bar('T1')).toHaveAttribute('aria-pressed', 'true')
  expect(bar('T2')).toHaveAttribute('aria-label', before)
  click('T2 predecessors'); fireEvent.click(screen.getByRole('checkbox', { name: 'T2 predecessor T1 — Research' })); click('Done')
  expect(bar('T2').getAttribute('aria-label')).not.toBe(before)
  expect(screen.getByRole('img', { name: 'Dependency T1 to T2' })).toBeInTheDocument()
})

test('the full form stages predecessor choices until Done and Enter inside the picker never submits the task', () => {
  render(<App />); add('Research', '5'); add('Draft')
  click('Edit T2')
  const before = bar('T2').getAttribute('aria-label')
  fireEvent.click(within(screen.getByRole('region', { name: 'Edit task T2' })).getByRole('button', { name: 'T2 predecessors' }))
  const choice = screen.getByRole('checkbox', { name: 'T2 predecessor T1 — Research' })
  fireEvent.click(choice); expect(bar('T2')).toHaveAttribute('aria-label', before)
  fireEvent.keyDown(choice, { key: 'Enter' })
  expect(screen.getByRole('region', { name: 'Edit task T2' })).toBeInTheDocument()
  expect(bar('T2').getAttribute('aria-label')).not.toBe(before)
  click('Save task')
  expect(screen.queryByRole('region', { name: 'Edit task T2' })).not.toBeInTheDocument()
})

test('the full form rejects dependency removal that would reactivate an invalid retained manual date', () => {
  render(<App />); add('First'); add('Second')
  click('Edit T2')
  fireEvent.change(screen.getByLabelText(/^Independent start date/), { target: { value: '2026-11-03' } })
  fireEvent.click(within(screen.getByRole('region', { name: 'Edit task T2' })).getByRole('button', { name: 'T2 predecessors' }))
  fireEvent.click(screen.getByRole('checkbox', { name: 'T2 predecessor T1 — First' })); click('Done'); click('Save task')
  tab('Project Settings')
  fireEvent.change(screen.getByLabelText('Project start date'), { target: { value: '2026-11-09' } }); fireEvent.blur(screen.getByLabelText('Project start date'))
  tab('Workspace'); click('Edit T2')
  const before = bar('T2').getAttribute('aria-label')
  fireEvent.click(within(screen.getByRole('region', { name: 'Edit task T2' })).getByRole('button', { name: 'T2 predecessors' }))
  fireEvent.click(screen.getByRole('checkbox', { name: 'T2 predecessor T1 — First' })); click('Done')
  expect(screen.getByRole('group', { name: 'T2 predecessor selection' })).toBeInTheDocument()
  expect(screen.getByRole('alert')).toHaveTextContent('manual requested start precedes')
  expect(bar('T2')).toHaveAttribute('aria-label', before)
  fireEvent.keyDown(screen.getByRole('checkbox', { name: 'T2 predecessor T1 — First' }), { key: 'Escape' })
  expect(screen.getByLabelText('Calculated Start')).toBeInTheDocument()
})
