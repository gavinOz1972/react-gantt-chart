import { chooseDependency, finishDependencies } from './dependencyHelpers'
import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function add(page: Page, name: string, hours: string) {
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Add task', exact: true }).click()
  await page.getByLabel(/^Task name/).fill(name)
  await page.getByLabel(/^Estimated duration/).fill(hours)
  await finishDependencies(page)
  await page.getByRole('button', { name: 'Save task' }).click()
}
async function sample(page: Page) {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByLabel(/^Working hours per day/).fill('2')
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByLabel(/^Working hours per day/).blur()
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByLabel('Target end date', { exact: true }).fill('2026-11-09')
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByLabel('Target end date', { exact: true }).blur()
  for (const day of ['Tuesday', 'Wednesday', 'Friday']) await page.getByRole('checkbox', { name: day, exact: true }).uncheck()
  await add(page, 'Research', '3')
  await add(page, 'Draft', '1')
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Edit T2', exact: true }).click()
  await page.getByText('Predecessors (0 selected)', { exact: true }).click()
  await chooseDependency(page, 'T1 — Research', true)
  await finishDependencies(page)
  await page.getByRole('button', { name: 'Save task' }).click()
  await add(page, 'Parallel review', '3')
  await add(page, 'Publish', '1')
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Edit T4', exact: true }).click()
  await page.getByText('Predecessors (0 selected)', { exact: true }).click()
  await chooseDependency(page, 'T2 — Draft', true)
  await chooseDependency(page, 'T3 — Parallel review', true)
  await finishDependencies(page)
  await page.getByRole('button', { name: 'Save task' }).click()
}
const bar = (page: Page, id: string) => page.getByRole('button', { name: new RegExp(`^${id} .*working hours; starts`) })

test('owner screenshots: expanded hatching and compressed work slots preserve selected task and source dates', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 1100 })
  await sample(page)
  const chart = page.getByRole('region', { name: 'Gantt chart', exact: true })
  await bar(page, 'T1').click()
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await expect(page.getByRole('row', { name: 'T1 Research', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(bar(page, 'T1')).toHaveAttribute('data-end', '3.5')
  await expect(bar(page, 'T1').locator('[data-kind=working]')).toHaveCount(2)
  await expect(chart.getByRole('img', { name: 'Dependency T1 to T2', exact: true })).toBeVisible()
  await expect(chart.getByRole('img', { name: 'Dependency T2 to T4', exact: true })).toBeVisible()
  await expect(chart.getByRole('img', { name: 'Dependency T3 to T4', exact: true })).toBeVisible()
  const details = await page.getByLabel('Selected task details', { exact: true }).textContent()
  await chart.screenshot({ path: info.outputPath('wp3-expanded.png') })
  for (const mode of ['Compressed', 'Expanded', 'Compressed']) {
    await chart.getByRole('button', { name: mode, exact: true }).click()
    await expect(bar(page, 'T1')).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByLabel('Selected task details', { exact: true })).toHaveText(details!)
  }
  await expect(bar(page, 'T1')).toHaveAttribute('data-end', '3')
  await expect(bar(page, 'T1').locator('.gantt-bar-outline')).toHaveAttribute('width', '120')
  await expect(bar(page, 'T1').locator('[data-kind=working]')).toHaveCount(0)
  await expect(chart.getByText('2026-11-03', { exact: true })).toHaveCount(0)
  await chart.screenshot({ path: info.outputPath('wp3-compressed.png') })
  const link = chart.getByRole('img', { name: 'Dependency T1 to T2', exact: true })
  await link.focus()
  await expect(link).toBeFocused()
  await expect(chart.getByRole('status')).toContainText('Dependency T1 to T2')
})

test('live upstream edits, checkbox removal, calendar edits and invalid drafts redraw the chart', async ({ page }) => {
  await sample(page)
  const chart = page.getByRole('region', { name: 'Gantt chart', exact: true })
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Edit T1', exact: true }).click()
  const before = await chart.getByRole('img', { name: 'Dependency T1 to T2', exact: true }).getAttribute('d')
  await page.getByLabel(/^Estimated duration/).fill('5')
  await expect(bar(page, 'T1')).toHaveAttribute('data-end', '7.5')
  await expect(chart.getByRole('img', { name: 'Dependency T1 to T2', exact: true })).not.toHaveAttribute('d', before!)
  await chart.getByRole('button', { name: 'Compressed', exact: true }).click()
  await expect(bar(page, 'T1')).toHaveAttribute('data-end', '5')
  await expect(bar(page, 'T2')).toHaveAttribute('data-start', '5')
  await finishDependencies(page)
  await page.getByRole('button', { name: 'Save task' }).click()
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Edit T2', exact: true }).click()
  await page.getByText('Predecessors (1 selected)', { exact: true }).click()
  await chooseDependency(page, 'T1 — Research', false)
  await expect(chart.getByRole('img', { name: 'Dependency T1 to T2', exact: true })).toHaveCount(0)
  await expect(bar(page, 'T2')).toHaveAttribute('data-start', '0')
  await finishDependencies(page)
  await page.getByRole('button', { name: 'Save task' }).click()
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Tuesday', exact: true }).check()
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await chart.getByRole('button', { name: 'Expanded', exact: true }).click()
  await expect(bar(page, 'T1')).toHaveAttribute('data-end', '3.5')
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByLabel(/^Working hours per day/).fill('4')
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByLabel(/^Working hours per day/).blur()
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await expect(bar(page, 'T1')).toHaveAttribute('data-end', '1.25')
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Edit T1', exact: true }).click()
  await page.getByLabel(/^Estimated duration/).fill('0')
  await expect(chart.getByText(/Timeline unavailable/)).toBeVisible()
  await expect(chart.getByRole('button', { name: /^T1 Research:/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(bar(page, 'T1')).toHaveAttribute('data-end', '1.25')
})

test('multiweek timeline scroll, zoom and sticky labels remain aligned at narrower desktop width', async ({ page }, info) => {
  await page.setViewportSize({ width: 900, height: 1000 })
  await sample(page)
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Edit T1', exact: true }).click()
  await page.getByLabel(/^Estimated duration/).fill('100')
  await finishDependencies(page)
  await page.getByRole('button', { name: 'Save task' }).click()
  const chart = page.getByRole('region', { name: 'Gantt chart', exact: true })
  const region = chart.getByRole('region', { name: 'Scrollable Gantt timeline', exact: true })
  await chart.getByRole('button', { name: 'Inspect T1 Research', exact: true }).click()
  const labelBefore = await chart.getByRole('button', { name: 'Inspect T1 Research', exact: true }).boundingBox()
  const nodes = await chart.locator('*').count()
  const start = performance.now()
  await region.evaluate(element => { element.scrollLeft = 3000; element.dispatchEvent(new Event('scroll')) })
  await expect.poll(async () => Number(await bar(page, 'T1').getAttribute('data-end'))).toBeGreaterThan(100)
  const labelAfter = await chart.getByRole('button', { name: 'Inspect T1 Research', exact: true }).boundingBox()
  expect(Math.abs(labelAfter!.x - labelBefore!.x)).toBeLessThan(2)
  expect(await chart.locator('*').count()).toBeLessThan(1500)
  expect(nodes).toBeLessThan(1500)
  expect(performance.now() - start).toBeLessThan(3000)
  await chart.getByRole('combobox', { name: 'Scale', exact: true }).selectOption('week')
  await expect(chart.getByText(/^Week of/).first()).toBeVisible()
  await expect(bar(page, 'T1')).toHaveAttribute('aria-pressed', 'true')
  await chart.screenshot({ path: info.outputPath('wp3-week-scale.png') })
  await chart.getByRole('button', { name: 'Compressed', exact: true }).click()
  await chart.getByRole('combobox', { name: 'Scale', exact: true }).selectOption('day')
  await chart.getByRole('button', { name: 'Go to selected task', exact: true }).click()
  await expect(chart.getByRole('button', { name: 'Inspect T1 Research', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
