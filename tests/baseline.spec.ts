import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { baselineInputs, establishedAt, snapshot } from '../src/test/baselineFixture'
import type { ProjectFile } from '../src/persistence/projectFile'
import { calculateSchedule } from '../src/domain'
import { openPlan } from './wp5-2-fixtures'

const fixture = { ...baselineInputs, schemaVersion: 1, format: 'react-gantt-chart', createdBy: 'React Gantt Chart', savedAt: establishedAt }
const key = 'react-gantt-chart:projects:v1'
const tab = (page: Page, name: string) => page.getByRole('tab', { name, exact: true }).click()
const panel = (page: Page) => page.getByRole('region', { name: 'Baseline plan', exact: true })
async function freeze(page: Page) {
  await tab(page, 'Project Settings')
  await page.getByRole('button', { name: 'Establish Baseline', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Establish baseline', exact: true }).click()
  await expect(panel(page).getByRole('button', { name: 'View Baseline', exact: true })).toBeVisible()
}
async function download(page: Page, button = 'Export JSON'): Promise<ProjectFile> {
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: button, exact: true }).click()
  const file = await pending
  return JSON.parse(await readFile((await file.path())!, 'utf8'))
}
async function exported(page: Page) { await tab(page, 'Files'); return download(page) }
async function inline(page: Page, label: string, value: string) {
  await page.getByRole('button', { name: `Edit ${label}`, exact: true }).click()
  await page.getByLabel(label, { exact: true }).fill(value)
  await page.getByLabel(label, { exact: true }).press('Enter')
}
async function importIntoOpen(page: Page, value: unknown) {
  await tab(page, 'Files')
  await page.getByLabel('Import project JSON', { exact: true }).setInputFiles({ name: 'baseline.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(value)) })
}

