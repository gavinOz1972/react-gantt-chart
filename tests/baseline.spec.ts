test('A09 malformed baseline imports never replace the open or saved plan', async ({ page }) => {
  await openPlan(page, fixture); await freeze(page)
  await tab(page, 'Files'); await page.getByLabel('Saved plan name', { exact: true }).fill('Safe baseline')
  await page.getByRole('button', { name: 'Save As', exact: true }).click()
  const saved = await page.evaluate(key => localStorage.getItem(key), key)
  const file = await exported(page)
  for (const baseline of [null, { ...snapshot(), schemaVersion: 99 }, { ...snapshot(), schedule: { tasks: [], projectCompletion: null } }]) {
    await importIntoOpen(page, { ...file, baseline })
    await expect(page.getByRole('alert')).toContainText(/BASELINE/)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect(await page.evaluate(key => localStorage.getItem(key), key)).toBe(saved)
    const stillOpen = await exported(page)
    expect(stillOpen.baseline).toEqual(file.baseline)
    expect(stillOpen.tasks).toEqual(file.tasks)
  }
})

