  await page.getByRole('button', { name: 'Establish Baseline', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('cannot be edited, overwritten or deleted')
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Cancel' })).toBeFocused()
