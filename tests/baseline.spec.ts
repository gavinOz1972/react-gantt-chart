  await expect(page.getByRole('button', { name: 'Establish Baseline', exact: true })).toBeFocused()
  expect((await exported(page)).baseline).toBeUndefined()
  await freeze(page)
  await page.getByRole('button', { name: 'View Baseline', exact: true }).click()
  const details = page.getByRole('region', { name: 'Read-only baseline tasks', exact: true })
  await expect(details).toContainText('Retained date 2026-11-12')
