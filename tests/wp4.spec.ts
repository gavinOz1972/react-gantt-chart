test('local save/reload and real JSON download/import preserve sources, retained manual dates and recalculated dates', async ({ page }, info) => {
  await page.setViewportSize({ width: 1100, height: 1100 })
  await calendar(page, '3', true)
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByLabel('Project name', { exact: true }).fill('Saved Semester')
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByLabel('Project name', { exact: true }).blur()
  await add(page, 'Research', '5')
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Edit T1', exact: true }).click()
  await page.getByLabel('Description', { exact: true }).fill('Carry research notes between computers')
  await page.getByLabel(/^Independent start date/).fill('2026-11-05')
  await finishDependencies(page)
  await page.getByRole('button', { name: 'Save task', exact: true }).click()
  await add(page, 'Parallel', '2')
  await add(page, 'Join', '1')
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Edit T3', exact: true }).click()
  await page.getByLabel(/^Independent start date/).fill('2026-11-12')
  await page.getByText('Predecessors (0 selected)', { exact: true }).click()
  await chooseDependency(page, 'T1 — Research', true)
  await chooseDependency(page, 'T2 — Parallel', true)
  await finishDependencies(page)
  await page.getByRole('button', { name: 'Save task', exact: true }).click()
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByLabel('Saved plan name', { exact: true }).fill('Semester backup')
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'Save As', exact: true }).click()
  await expect(page.getByText('Saved locally', { exact: true })).toBeVisible()
  const snapshot = await page.locator('tbody tr').allTextContents()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click()
  const download = await downloadPromise
  const json = await readFile((await download.path())!, 'utf8')
  const exported = JSON.parse(json)
  expect(exported.schemaVersion).toBe(4)
  expect(exported).not.toHaveProperty('baseline')
  expect(exported.tasks[2].requestedStartDate).toBe('2026-11-12')
  expect(exported).not.toHaveProperty('schedule')
  expect(exported).not.toHaveProperty('analysis')
  await page.reload()
  await page.getByRole('combobox', { name: 'Saved plans', exact: true }).selectOption('Semester backup')
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'Load project', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(3)
  expect(await page.locator('tbody tr').allTextContents()).toEqual(snapshot)
  await expect(page.getByLabel(/^Working hours per day/)).toHaveValue('3')
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Tuesday', exact: true })).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Thursday', exact: true })).toBeChecked()
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await expect(page.getByText('Your project starts with one task', { exact: true })).toBeVisible()
  await page.getByLabel('Import project JSON', { exact: true }).setInputFiles({ name: download.suggestedFilename(), mimeType: 'application/json', buffer: Buffer.from(json) })
  await expect(page.locator('tbody tr')).toHaveCount(3)
  expect(await page.locator('tbody tr').allTextContents()).toEqual(snapshot)
  await expect(page.getByText('Unsaved changes', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('region', { name: 'Save & reopen', exact: true }).screenshot({ path: info.outputPath('wp4-local-projects.png') })
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Edit T3', exact: true }).click()
  await expect(page.getByText('Retained independent date: 2026-11-12. It will apply again if you remove all predecessors.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Add task', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Add task T4', exact: true })).toBeVisible()
})

test('bad imports are atomic; unsaved replacement, saved overwrite and deletion require confirmation', async ({ page }) => {
  await calendar(page)
  await add(page, 'Keep this task', '1')
  await add(page, 'Keep the dependent', '1')
  await predecessor(page, 'T2', ['T1 — Keep this task'])
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByLabel('Saved plan name', { exact: true }).fill('Safe copy')
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'Save As', exact: true }).click()
  const raw = await page.evaluate(key => localStorage.getItem(key)!, libraryKey)
  const original = JSON.parse(raw).projects[0].plan
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await page.getByRole('button', { name: 'Edit T1', exact: true }).click()
  await page.getByLabel(/^Estimated duration/).fill('0')
  const missing = structuredClone(original); missing.tasks[1].predecessorTaskIds = ['missing']
  const cycle = structuredClone(original); cycle.tasks[0].predecessorTaskIds = ['T2']
  const cases = [
    { text: '{broken', error: 'INVALID_JSON' },
    { text: JSON.stringify({ ...original, schemaVersion: 999 }), error: 'UNSUPPORTED_VERSION' },
    { text: JSON.stringify(missing), error: 'MISSING_PREDECESSOR' },
    { text: JSON.stringify(cycle), error: 'DEPENDENCY_CYCLE' },
  ]
  const storage = page.getByRole('region', { name: 'Save & reopen', exact: true })
  for (const candidate of cases) {
    await page.getByRole('tab', { name: 'Files', exact: true }).click()
    await page.getByLabel('Import project JSON', { exact: true }).setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from(candidate.text) })
    await expect(storage.getByRole('alert')).toContainText(candidate.error)
    await expect(page.getByLabel(/^Estimated duration/)).toHaveValue('0')
    expect(await page.evaluate(key => localStorage.getItem(key), libraryKey)).toBe(raw)
  }
  await page.getByLabel('Import project JSON', { exact: true }).setInputFiles({ name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) })
  await expect(page.getByRole('dialog')).toContainText('Replace unsaved work?')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByLabel(/^Estimated duration/)).toHaveValue('0')
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'Load project', exact: true }).click()
  await page.getByRole('button', { name: 'Replace current project', exact: true }).click()
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await expect(page.getByRole('row', { name: 'T1 Keep this task', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await expect(page.getByRole('row', { name: 'T2 Keep the dependent', exact: true })).toBeVisible()
  await expect(page.getByLabel(/^Estimated duration/)).toHaveCount(0)
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByLabel('Project name', { exact: true }).fill('Revised project')
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await page.getByLabel('Project name', { exact: true }).blur()
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'Save As', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Overwrite saved plan')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(await page.evaluate(key => localStorage.getItem(key), libraryKey)).toBe(raw)
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'Save As', exact: true }).click()
  await page.getByRole('button', { name: 'Overwrite saved plan', exact: true }).click()
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'Delete saved plan', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('open project and other saved plans will be kept')
  await page.getByRole('button', { name: 'Delete saved copy', exact: true }).click()
  await page.getByRole('tab', { name: 'Workspace', exact: true }).click()
  await expect(page.getByRole('row', { name: 'T1 Keep this task', exact: true })).toBeVisible()
  await expect(page.getByText('Unsaved changes', { exact: true })).toBeVisible()
})
