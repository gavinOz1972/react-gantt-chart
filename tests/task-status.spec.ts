import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import type { ProjectFile } from '../src/persistence/projectFile'
import { workBaseline, workData, workRecords, workTimestamp } from '../src/test/workFixture'
import { openPlan } from './wp5-2-fixtures'

const fixture = { ...workData, schemaVersion: 3, format: 'react-gantt-chart', createdBy: 'React Gantt Chart', savedAt: workTimestamp, baseline: workBaseline(), workTracking: workRecords() }
const libraryKey = 'react-gantt-chart:projects:v1'
const tab = (page: Page, name: string) => page.getByRole('tab', { name, exact: true }).click()
const status = (page: Page, id = 'T2', context = 'table') => page.getByRole('combobox', { name: `${id} status in ${context}`, exact: true })
const panel = (page: Page) => page.getByRole('region', { name: 'Status & completion', exact: true })
const work = (page: Page) => page.getByRole('region', { name: 'Work & effort', exact: true })
const modal = (page: Page) => page.getByRole('dialog')
async function open(page: Page) { await openPlan(page, fixture) }
async function select(page: Page, id = 'T2') { await tab(page, 'Workspace'); await page.getByRole('button', { name: `Select ${id} in chart`, exact: true }).click() }
async function criterion(page: Page, text = 'Login accepts valid credentials') {
  await panel(page).getByRole('button', { name: 'Add criterion', exact: true }).click()
  await panel(page).getByLabel('Completion criterion', { exact: true }).fill(text)
  await panel(page).getByRole('button', { name: 'Save criterion', exact: true }).click()
}
async function complete(page: Page, date = '2026-10-30') {
  await panel(page).getByRole('button', { name: 'Mark Complete', exact: true }).click()
  await modal(page).getByLabel('Effective completion date', { exact: true }).fill(date)
  const checks = modal(page).getByRole('checkbox')
  for (const check of await checks.all()) await check.check()
  await modal(page).getByRole('button', { name: 'Confirm completion', exact: true }).click()
  await expect(modal(page)).toHaveCount(0)
}
async function download(page: Page, label = 'Export JSON'): Promise<ProjectFile> {
  const pending = page.waitForEvent('download'); await page.getByRole('button', { name: label, exact: true }).click()
  const result = await pending
  return JSON.parse(await readFile((await result.path())!, 'utf8'))
}
async function exported(page: Page) { await tab(page, 'Files'); return download(page) }
async function save(page: Page, name = 'Status plan') {
  await tab(page, 'Files'); await page.getByLabel('Saved plan name', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Save As', exact: true }).click()
  await expect(page.getByText('Saved locally', { exact: true })).toBeVisible()
}

