test('A13 corrupt enum, duplicate event IDs, orphan references and malformed snapshots reject atomically', async ({ page }) => {
  await open(page); await select(page); await criterion(page); await complete(page); await save(page)
  const before = await exported(page); const original = before.taskProgress!
  const saved = await page.evaluate(key => localStorage.getItem(key), libraryKey)
  for (const taskProgress of [
    { ...original, tasks: { ...original.tasks, T2: { ...original.tasks.T2, status: 'Ready for Review' } } },
    { ...original, events: [...original.events, original.events[0]] },
    { ...original, events: [{ ...original.events[0], taskId: 'missing' }] },
    { ...original, events: [{ ...original.events[0], criteriaSnapshot: [{ ...original.events[0].criteriaSnapshot![0], checked: false }] }] },
  ]) {
    await page.getByLabel('Import project JSON', { exact: true }).setInputFiles({ name: 'bad-status.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...before, taskProgress })) })
    await expect(page.getByRole('alert')).toContainText(/STATUS|COMPLETION/)
    await expect(modal(page)).toHaveCount(0)
    expect(await page.evaluate(key => localStorage.getItem(key), libraryKey)).toBe(saved)
    expect((await exported(page)).taskProgress).toEqual(original)
  }
})

