test('A09/A10/A13 real Enter/Tab/blur commits and Escape cancellation keep invalid drafts out of Gantt and CPM', async ({ page }) => {
  await open(page)
  const before = await bar(page, 'T1').getAttribute('aria-label')
  await inline(page, 'T1 duration', '0')
  await expect(page.getByRole('alert')).toContainText('positive safe whole number')
  await expect(bar(page, 'T1')).toHaveAttribute('aria-label', before!)
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeDisabled()
  await tab(page, 'Files'); await tab(page, 'Workspace')
  await expect(page.getByLabel('T1 duration', { exact: true })).toHaveValue('0')
  await page.getByLabel('T1 duration', { exact: true }).press('Escape')
  await expect(page.getByRole('button', { name: 'Edit T1 duration', exact: true })).toBeFocused()
  await inline(page, 'T1 name', 'Discard rename', 'Escape')
  await expect(row(page, 'T1')).toHaveAttribute('aria-label', 'T1 Research')
  for (const [value, key] of [['9', 'Enter'], ['4', 'Tab']]) {
    await inline(page, 'T1 duration', value, key)
    await expect(bar(page, 'T1')).toHaveAttribute('aria-label', new RegExp(`${value} working hours;`))
    await expect(page.getByLabel('T1 duration', { exact: true })).toHaveCount(0)
  }
  await page.getByRole('button', { name: 'Edit T1 duration', exact: true }).click()
  await page.getByLabel('T1 duration', { exact: true }).fill('6')
  await page.getByRole('tab', { name: 'Project Settings', exact: true }).click()
  await tab(page, 'Workspace')
  await expect(bar(page, 'T1')).toHaveAttribute('aria-label', /6 working hours;/)
  await page.getByRole('checkbox', { name: 'Highlight Critical Path', exact: true }).check()
  await expect(bar(page, 'T1')).toHaveAttribute('data-critical', 'false')
  await page.getByRole('button', { name: 'Select T4 in chart', exact: true }).click()
  await page.getByRole('button', { name: 'Go to selected task', exact: true }).click()
  await expect(bar(page, 'T4')).toHaveAttribute('data-critical', 'true')
})

test('A11/A12 multiline text, independent date picker and immediate checkbox commits preserve retained dates and reject cycles', async ({ page }) => {
  await open(page)
  await page.getByRole('button', { name: 'Edit T1 description', exact: true }).click()
  const notes = page.getByLabel('T1 description', { exact: true })
  await notes.fill('First line'); await notes.press('End'); await notes.press('Enter'); await notes.pressSequentially('Second line')
  await expect(notes).toHaveValue('First line\nSecond line')
  await notes.press('Control+Enter')
  await expect(page.getByRole('button', { name: 'Edit T1 description', exact: true })).toHaveText('First line\nSecond line')
  await inline(page, 'T1 description', 'Cancelled notes', 'Escape')
  await expect(page.getByRole('button', { name: 'Edit T1 description', exact: true })).toHaveText('First line\nSecond line')
  await page.getByRole('button', { name: 'Edit T4 independent start date', exact: true }).click()
  await expect(page.getByLabel('T4 independent start date', { exact: true })).toHaveAttribute('type', 'date')
  await page.getByLabel('T4 independent start date', { exact: true }).fill('2026-11-13')
  await page.getByLabel('T4 independent start date', { exact: true }).press('Enter')
  await expect(row(page, 'T4')).toContainText('2026-11-13')
  await row(page, 'T5').locator('summary').click()
  await page.getByRole('checkbox', { name: 'T5 predecessor T1 — Research', exact: true }).uncheck()
  await expect(row(page, 'T1')).toBeVisible()
  await page.getByRole('checkbox', { name: 'T5 predecessor T4 — Notes', exact: true }).uncheck()
  await expect(row(page, 'T5')).toContainText('2026-11-16')
  await expect(row(page, 'T5').getByRole('button', { name: 'Edit T5 independent start date', exact: true })).toBeVisible()
  await row(page, 'T1').locator('summary').click()
  await expect(page.getByRole('checkbox', { name: 'T1 predecessor T2 — Implementation', exact: true })).toBeDisabled()
  await expect(page.getByRole('checkbox', { name: 'T1 predecessor T1 — Research', exact: true })).toBeDisabled()
  await expect(row(page, 'T2').getByRole('button', { name: /independent start date/ })).toHaveCount(0)
})

