import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function add(page: Page, name: string, hours = '1') {
  await page.getByRole('button', { name: 'Add task', exact: true }).click()
  await page.getByLabel(/^Task name/).fill(name)
  await page.getByLabel(/^Estimated duration/).fill(hours)
  await page.getByRole('button', { name: 'Save task' }).click()
}

test('desktop task workflow, dependencies, recalculation and confirmed deletion', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 1100 })
  await page.goto('/')
  await page.getByLabel(/^Working hours per day/).fill('2')
  await page.getByLabel(/^Working hours per day/).press('Tab')
  for (const day of ['Tuesday', 'Wednesday', 'Friday']) await page.getByRole('checkbox', { name: day, exact: true }).uncheck()
  await add(page, 'Research', '3')
  await expect(page.getByRole('row', { name: 'T1 Research', exact: true })).toContainText('2026-11-05')
  await add(page, 'Draft')
  await page.getByRole('button', { name: 'Edit T2', exact: true }).click()
  await page.getByText('Predecessors (0 selected)', { exact: true }).click()
  await page.getByRole('checkbox', { name: 'T1 — Research', exact: true }).check()
  await expect(page.getByLabel('Calculated Start', { exact: true })).toContainText('2026-11-05 · hour 2')
  await expect(page.getByLabel(/^Independent start date/)).toHaveCount(0)
  await page.getByRole('button', { name: 'Save task' }).click()
  await add(page, 'Review', '2')
  await page.getByRole('button', { name: 'Edit T3', exact: true }).click()
  await page.getByText('Predecessors (0 selected)', { exact: true }).click()
  await page.getByRole('checkbox', { name: 'T1 — Research', exact: true }).check()
  await page.getByRole('checkbox', { name: 'T2 — Draft', exact: true }).check()
  await expect(page.getByText('Predecessors (2 selected)', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save task' }).click()
  await page.getByRole('button', { name: 'Edit T1', exact: true }).click()
  await page.getByLabel(/^Estimated duration/).fill('5')
  await expect(page.getByRole('row', { name: 'T2 Draft', exact: true })).toContainText('2026-11-09')
  await page.getByText('Predecessors (0 selected)', { exact: true }).click()
  await expect(page.getByRole('checkbox', { name: /^T2 — Draft/ })).toBeDisabled()
  await expect(page.getByText(/Remove a dependency to break this cycle/).first()).toBeVisible()
  await page.getByRole('button', { name: 'Save task' }).click()
  await page.getByRole('button', { name: 'Edit T2', exact: true }).click()
  await page.getByText('Predecessors (1 selected)', { exact: true }).click()
  await page.getByRole('checkbox', { name: 'T1 — Research', exact: true }).uncheck()
  await expect(page.getByLabel(/^Independent start date/)).toBeVisible()
  await page.getByRole('button', { name: 'Save task' }).click()
  await expect(page.getByRole('row', { name: 'T1 Research', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Delete T1', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('T3 — Review: remove predecessor T1')
  await expect(page.getByRole('button', { name: 'Keep task' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Delete T1', exact: true }).click()
  await page.getByRole('button', { name: 'Delete task and remove links' }).click()
  await expect(page.getByRole('row', { name: 'T1 Research', exact: true })).toHaveCount(0)
  await expect(page.getByRole('row', { name: 'T3 Review', exact: true })).toContainText('T2 — Draft')
  await page.getByLabel('Target end date', { exact: true }).fill('2026-11-02')
  await page.getByLabel('Target end date', { exact: true }).press('Tab')
  await expect(page.getByText('Late', { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('desktop.png'), fullPage: true })
})

test('date controls, keyboard focus, manual reset and recoverable errors at narrower width', async ({ page }, info) => {
  await page.setViewportSize({ width: 780, height: 1000 })
  await page.goto('/')
  await page.getByLabel('Project name', { exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Project start date', { exact: true })).toBeFocused()
  await expect(page.getByLabel('Project start date', { exact: true })).toHaveAttribute('type', 'date')
  await page.getByLabel('Project start date', { exact: true }).press('Alt+ArrowDown')
  await page.screenshot({ path: info.outputPath('date-picker.png'), fullPage: true })
  await page.keyboard.press('Escape')
  await page.getByLabel('Project start date', { exact: true }).fill('2026-11-03')
  await page.getByLabel('Project start date', { exact: true }).press('Tab')
  await expect(page.getByLabel('Project start date', { exact: true })).toHaveValue('2026-11-03')
  await add(page, 'Read sources', '3')
  await expect(page.getByRole('button', { name: 'Add task', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Edit T1', exact: true }).click()
  await expect(page.getByLabel(/^Task name/)).toBeFocused()
  await page.getByLabel(/^Independent start date/).fill('2026-11-12')
  await page.getByRole('button', { name: 'Save task' }).click()
  await page.getByLabel('Project start date', { exact: true }).fill('2026-11-05')
  await page.getByLabel('Project start date', { exact: true }).press('Tab')
  await expect(page.getByRole('row', { name: 'T1 Read sources', exact: true })).toContainText('2026-11-12')
  await page.getByRole('button', { name: 'Edit T1', exact: true }).click()
  await page.getByRole('button', { name: 'Reset to Project Start' }).click()
  await page.getByLabel(/^Estimated duration/).fill('0.5')
  await expect(page.getByRole('alert')).toContainText('positive safe whole number')
  await expect(page.getByRole('row', { name: 'T1 Read sources', exact: true })).not.toContainText('2026-11-12')
  await expect(page.getByRole('button', { name: 'Save task' })).toBeDisabled()
  await page.screenshot({ path: info.outputPath('narrow-validation.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByLabel(/^Estimated duration/).fill('2')
  await page.getByRole('button', { name: 'Save task' }).click()
  await expect(page.getByRole('row', { name: 'T1 Read sources', exact: true })).toContainText('2026-11-05')
  await page.getByLabel('Target end date', { exact: true }).fill('2026-11-01')
  await page.getByLabel(/^Target end date/).press('Tab')
  await expect(page.getByRole('alert')).toContainText('target end date precedes')
  await page.getByRole('button', { name: 'Revert settings' }).click()
  await expect(page.getByLabel('Target end date', { exact: true })).toHaveValue('2026-12-18')
})
